"""Chunking / retrieval ablations (deterministic, no API calls).

    uv run python -m eval.experiments

Builds one throwaway index per chunking variant under .cache/exp/ and reports
hit@3, hit@6, MRR@6 for hybrid, vector-only and BM25-only retrieval. Output is
printed as a markdown table and saved to eval/experiments.md.
"""

from __future__ import annotations

import contextlib
import io
from pathlib import Path

from eval.run_eval import load_golden, retrieval_metrics
from rag import config

VARIANTS = [
    # name, target, max, min, overlap, headings
    ("fixed-600 (no headings)", 600, 800, 600, 0.15, False),
    ("heading-aware 600/min200", 600, 800, 200, 0.15, True),
    ("heading-aware 600/min450", 600, 800, 450, 0.15, True),
    ("heading-aware 350/min150", 350, 500, 150, 0.15, True),
    ("heading-aware 600/min450, no overlap", 600, 800, 450, 0.0, True),
]


def use_index(path: Path) -> None:
    config.INDEX_DIR = path
    config.CHROMA_DIR = path / "chroma"
    config.CHUNKS_FILE = path / "chunks.jsonl"
    config.BM25_FILE = path / "bm25.pkl"


def main() -> None:
    from rag.ingest import build_index
    from rag.retrieve import BGE_QUERY_PREFIX, Retriever

    golden = load_golden()
    lines = ["| Chunking | Retrieval | chunks | hit@3 | hit@6 | MRR@6 |", "|---|---|---|---|---|---|"]
    base = config.ROOT / ".cache" / "exp"
    for name, tgt, mx, mn, ov, head in VARIANTS:
        config.CHUNK_TARGET_TOKENS, config.CHUNK_MAX_TOKENS, config.CHUNK_MIN_TOKENS = tgt, mx, mn
        config.CHUNK_OVERLAP, config.CHUNK_HEADINGS = ov, head
        slug = "".join(ch if ch.isalnum() else "_" for ch in name)
        use_index(base / slug)
        with contextlib.redirect_stdout(io.StringIO()):
            build_index(rebuild=True)
        r = Retriever.load()
        for mode in ("hybrid", "vector", "bm25"):
            m3 = retrieval_metrics(r, golden, 3, mode)
            m6 = retrieval_metrics(r, golden, 6, mode)
            lines.append(f"| {name} | {mode} | {r.size} | {m3['hit']:.3f} | {m6['hit']:.3f} | {m6['mrr']:.3f} |")
            print(lines[-1], flush=True)
        if name == "heading-aware 600/min450":
            r.query_prefix = ""
            for mode in ("hybrid", "vector"):
                m3 = retrieval_metrics(r, golden, 3, mode)
                m6 = retrieval_metrics(r, golden, 6, mode)
                lines.append(f"| {name}, no bge query prefix | {mode} | {r.size} | {m3['hit']:.3f} | "
                             f"{m6['hit']:.3f} | {m6['mrr']:.3f} |")
                print(lines[-1], flush=True)
            r.query_prefix = BGE_QUERY_PREFIX
    out = config.ROOT / "eval" / "experiments.md"
    out.write_text("# Retrieval ablations\n\nGenerated by `eval/experiments.py` "
                   f"({sum(g['answerable'] for g in golden)} answerable golden questions).\n\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
