# Relative frequency of work orders by asset type (conveyors dominate a hub).
ASSET_WEIGHTS = {
    "belt conveyor": 22, "sorter induction": 12, "VFD drive": 15, "photo-eye sensor": 18,
    "gearbox": 10, "UPS": 6, "CRAC/CRAH cooling unit": 9, "PDU": 8,
}
TECHS = ["T-101", "T-114", "T-127", "T-133", "T-148", "T-152"]


def generate(rows: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    start = date(2025, 1, 6)
    out = []
    types = list(ASSET_WEIGHTS)
    weights = [ASSET_WEIGHTS[t] for t in types]
    for _ in range(rows):
        atype = rng.choices(types, weights)[0]
        prefix, count, modes = CATALOG[atype]
        mode = rng.choices(modes, [m[0] for m in modes])[0]
        _, symptom, code, cause, action, (lo, hi), notes = mode
        d = start + timedelta(days=rng.randint(0, 364))
        note = rng.choice(notes) + f". Tech {rng.choice(TECHS)}."
        out.append({
            "wo_id": "",  # assigned after sorting by date
            "date": d.isoformat(),
            "asset_type": atype,
            "asset_id": f"{prefix}-{rng.randint(1, count):03d}",
            "symptom": symptom,
            "fault_code": code,
            "root_cause": cause,
            "action_taken": action,
            "downtime_min": rng.randint(lo, hi),
            "technician_notes": note,
        })
    out.sort(key=lambda r: (r["date"], r["asset_id"]))
    for n, r in enumerate(out, 1):
        r["wo_id"] = f"WO-{n:05d}"
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=300)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    rows = generate(args.rows, args.seed)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", newline="") as f:
        f.write(HEADER_COMMENT)
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} synthetic work orders -> {OUT}")


if __name__ == "__main__":
    main()
